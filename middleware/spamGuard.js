// Строгая защита от спама: 10 запросов за 30 минут — и этот IP получает
// отказ до конца 30-минутного окна. Блокируется именно тот, кто спамит
// (ключ — IP-адрес), у остальных посетителей свой отдельный счётчик,
// сервер продолжает работать как обычно.
//
// СОЗНАТЕЛЬНО не накладываем это на вообще все запросы (GET /api/games,
// /api/auth/me и т.п.) — одна обычная загрузка сайта уже делает 5-8 таких
// запросов, и обычный человек сам себя заблокировал бы за пару обновлений
// страницы. Применяем только к действиям, где спам реально возможен и вреден:
// вход/регистрация, создание заказа, отправка пополнения, проверка ID.
const rateLimit = require('express-rate-limit');

function spamGuard(message) {
  return rateLimit({
    windowMs: 30 * 60 * 1000,
    max: 10,
    standardHeaders: true,
    legacyHeaders: false,
    message: { error: message || 'Слишком много попыток. Попробуйте снова через 30 минут.' }
  });
}

module.exports = { spamGuard };
